// ONE command -> real full-page screenshots for ALL your client sites,
// and the portfolio picks them up automatically (no path editing).
//
// Setup (once):   npm i playwright sharp   (needs Chrome or Edge installed; no browser download needed)
// Add a site:     add a line in tools/sites.json  (slug must match the `slug` in js/projects-data.js)
// Capture all:    node tools/capture-all.mjs
// Capture one:    node tools/capture-all.mjs stone-bazar
//
// Per site you can optionally set:
//   "hide": [".cookie-banner", "#chat-widget"]   CSS selectors hidden before the screenshot
//   "wait": 2500                                  extra ms to wait (heavy/animated sites)
//
// Output: images/client-work/<slug>-desktop|tablet|mobile.webp (or .jpg if taller than 16 383px)
//         js/screenshots-manifest.js (read by the site: it swaps the placeholders for you)
import { chromium } from "playwright";
import sharp from "sharp";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";

const OUT = "images/client-work";
const MANIFEST = "js/screenshots-manifest.js";
mkdirSync(OUT, { recursive: true });

const sites = JSON.parse(readFileSync("tools/sites.json", "utf8"));
const only = process.argv.slice(2);
const todo = only.length ? sites.filter((s) => only.includes(s.slug)) : sites;
if (!todo.length) { console.error("No matching site in tools/sites.json"); process.exit(1); }

const VIEWPORTS = [
  { key: "desktop", width: 1440, height: 900, scale: 1 },
  { key: "tablet", width: 820, height: 1180, scale: 1 },
  { key: "mobile", width: 390, height: 844, scale: 2 },
];

function readManifest() {
  if (!existsSync(MANIFEST)) return {};
  const m = readFileSync(MANIFEST, "utf8").match(/window\.CLIENT_SHOTS\s*=\s*(\{[\s\S]*?\});/);
  try { return m ? JSON.parse(m[1]) : {}; } catch { return {}; }
}
function writeManifest(obj) {
  writeFileSync(MANIFEST,
`/* AUTO-GENERATED by tools/capture-all.mjs — do not edit by hand. */
window.CLIENT_SHOTS = ${JSON.stringify(obj, null, 2)};
`);
}

// Scroll slowly so lazy images and reveal-on-scroll animations render, then go back to top.
async function warmUp(page) {
  await page.evaluate(async () => {
    const step = Math.round(innerHeight * 0.6);
    for (let y = 0; y < document.documentElement.scrollHeight; y += step) {
      scrollTo(0, y);
      await new Promise((r) => setTimeout(r, 250));
    }
    scrollTo(0, 0);
  });
  await page.waitForTimeout(800);
}

// Uses Playwright's Chromium if installed, otherwise falls back to the Chrome or Edge
// already on your computer (so `npx playwright install` is NOT required).
async function launchBrowser() {
  const attempts = [];
  if (process.env.CHROMIUM_PATH) attempts.push({ executablePath: process.env.CHROMIUM_PATH });
  attempts.push({}, { channel: "chrome" }, { channel: "msedge" });
  for (const opts of attempts) {
    try { return await chromium.launch(opts); } catch { /* try the next one */ }
  }
  console.error("Could not start a browser. Install Google Chrome or Microsoft Edge, or set CHROMIUM_PATH to its .exe file.");
  process.exit(1);
}
const browser = await launchBrowser();
const manifest = readManifest();

for (const site of todo) {
  console.log(`\n▶ ${site.slug}  ${site.url}`);
  const shots = {};
  for (const v of VIEWPORTS) {
    let png, height, scale = v.scale;
    for (;;) { // if the 2x image is too tall for WebP, retry at 1x
      const ctx = await browser.newContext({
        viewport: { width: v.width, height: v.height }, deviceScaleFactor: scale,
        isMobile: v.key === "mobile", hasTouch: v.key !== "desktop",
      });
      const page = await ctx.newPage();
      try {
        await page.goto(site.url, { waitUntil: "networkidle", timeout: 60000 });
      } catch (e) {
        console.error(`  ✗ could not open ${site.url}: ${e.message.split("\n")[0]}`);
        await ctx.close(); png = null; break;
      }
      if (site.hide?.length) await page.addStyleTag({ content: `${site.hide.join(",")}{display:none!important}` });
      await page.waitForTimeout(site.wait ?? 1000);
      await warmUp(page);
      png = await page.screenshot({ fullPage: true, type: "png" });
      ({ height } = await sharp(png).metadata());
      await ctx.close();
      if (height <= 16383 || scale === 1) break;
      scale = 1;
    }
    if (!png) break;
    const base = `${OUT}/${site.slug}-${v.key}`;
    const ext = height <= 16383 ? "webp" : "jpg";
    await (ext === "webp" ? sharp(png).webp({ quality: 85, effort: 5 }) : sharp(png).jpeg({ quality: 85, mozjpeg: true })).toFile(`${base}.${ext}`);
    shots[v.key] = `./${base}.${ext}`;
    console.log(`  ✓ ${v.key.padEnd(7)} ${base}.${ext}  (${height}px tall)`);
  }
  if (Object.keys(shots).length === VIEWPORTS.length) manifest[site.slug] = shots;
}
await browser.close();
writeManifest(manifest);
console.log(`\nDone. Updated ${MANIFEST}. Refresh your portfolio.`);
